# for loop:it is used to iterate through a sequence like list,tuple,or string

l=[1,2,3,4]
for item in l:
    print(item)


# Range(): it is used to generate the sequence  of a number 
#  we can spaecify the start,stop,step_size as  follows
# range(start,stop,step_size)

for i in range(10):
    print(i)





